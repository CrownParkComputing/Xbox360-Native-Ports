// AES-128 known-answer tests.
//
// The vectors below are from FIPS-197 and NIST SP 800-38A, so this checks the
// implementation against the standard rather than against itself. A silently
// wrong AES would surface much later as a XEX that decrypts to garbage, which
// is a far more expensive thing to debug than a failing vector here.
#include "whitty_xenon/aes.h"

#include <cassert>
#include <cstdio>
#include <cstring>
#include <vector>

using namespace whitty_xenon;

namespace {

bool same(const uint8_t* a, const uint8_t* b, std::size_t size) {
    return std::memcmp(a, b, size) == 0;
}

void test_fips197_appendix_c1() {
    // FIPS-197 Appendix C.1, AES-128.
    const uint8_t key[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                             0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    const uint8_t plain[16] = {0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
                               0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff};
    const uint8_t cipher[16] = {0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
                                0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a};

    uint8_t out[16];
    aes128_encrypt_block(key, plain, out);
    assert(same(out, cipher, 16));

    aes128_decrypt_block(key, cipher, out);
    assert(same(out, plain, 16));
}

void test_fips197_appendix_b() {
    // FIPS-197 Appendix B worked example.
    const uint8_t key[16] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
                             0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    const uint8_t plain[16] = {0x32, 0x43, 0xf6, 0xa8, 0x88, 0x5a, 0x30, 0x8d,
                               0x31, 0x31, 0x98, 0xa2, 0xe0, 0x37, 0x07, 0x34};
    const uint8_t cipher[16] = {0x39, 0x25, 0x84, 0x1d, 0x02, 0xdc, 0x09, 0xfb,
                                0xdc, 0x11, 0x85, 0x97, 0x19, 0x6a, 0x0b, 0x32};
    uint8_t out[16];
    aes128_encrypt_block(key, plain, out);
    assert(same(out, cipher, 16));
    aes128_decrypt_block(key, cipher, out);
    assert(same(out, plain, 16));
}

void test_in_place_block_operation() {
    // The XEX loader decrypts into the same buffer it read into.
    const uint8_t key[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                             0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    uint8_t buffer[16] = {0x69, 0xc4, 0xe0, 0xd8, 0x6a, 0x7b, 0x04, 0x30,
                          0xd8, 0xcd, 0xb7, 0x80, 0x70, 0xb4, 0xc5, 0x5a};
    const uint8_t plain[16] = {0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
                               0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff};
    aes128_decrypt_block(key, buffer, buffer);
    assert(same(buffer, plain, 16));
}

void test_cbc_vector_sp800_38a() {
    // NIST SP 800-38A F.2.2, CBC-AES128.Decrypt (first two blocks).
    const uint8_t key[16] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
                             0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    uint8_t iv[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                      0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    const uint8_t cipher[32] = {
        0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46, 0xce, 0xe9, 0x8e,
        0x9b, 0x12, 0xe9, 0x19, 0x7d, 0x50, 0x86, 0xcb, 0x9b, 0x50, 0x72,
        0x19, 0xee, 0x95, 0xdb, 0x11, 0x3a, 0x91, 0x76, 0x78, 0xb2};
    const uint8_t expected[32] = {
        0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e,
        0x11, 0x73, 0x93, 0x17, 0x2a, 0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03,
        0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51};

    uint8_t out[32];
    assert(aes128_cbc_decrypt(key, iv, cipher, out, sizeof(cipher)));
    assert(same(out, expected, sizeof(expected)));
}

void test_cbc_chains_across_calls() {
    // The image loader decrypts a stream piecewise as it walks compression
    // blocks, so decrypting in two calls must equal decrypting in one.
    const uint8_t key[16] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
                             0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    const uint8_t cipher[32] = {
        0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46, 0xce, 0xe9, 0x8e,
        0x9b, 0x12, 0xe9, 0x19, 0x7d, 0x50, 0x86, 0xcb, 0x9b, 0x50, 0x72,
        0x19, 0xee, 0x95, 0xdb, 0x11, 0x3a, 0x91, 0x76, 0x78, 0xb2};
    const uint8_t start_iv[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                                  0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};

    uint8_t whole[32];
    uint8_t iv_a[16];
    std::memcpy(iv_a, start_iv, 16);
    assert(aes128_cbc_decrypt(key, iv_a, cipher, whole, 32));

    uint8_t split[32];
    uint8_t iv_b[16];
    std::memcpy(iv_b, start_iv, 16);
    assert(aes128_cbc_decrypt(key, iv_b, cipher, split, 16));
    assert(aes128_cbc_decrypt(key, iv_b, cipher + 16, split + 16, 16));

    assert(same(whole, split, 32));
    // Both routes must leave the same chaining state behind.
    assert(same(iv_a, iv_b, 16));
}

void test_cbc_in_place_and_bad_sizes() {
    const uint8_t key[16] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
                             0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    uint8_t iv[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07,
                      0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    uint8_t buffer[16] = {0x76, 0x49, 0xab, 0xac, 0x81, 0x19, 0xb2, 0x46,
                          0xce, 0xe9, 0x8e, 0x9b, 0x12, 0xe9, 0x19, 0x7d};
    const uint8_t expected[16] = {0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96,
                                  0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a};
    assert(aes128_cbc_decrypt(key, iv, buffer, buffer, 16));
    assert(same(buffer, expected, 16));

    // A partial block is a caller error, not something to guess at.
    uint8_t iv2[16] = {0};
    uint8_t out[16];
    assert(!aes128_cbc_decrypt(key, iv2, buffer, out, 15));
    // Zero length is a no-op, not an error.
    assert(aes128_cbc_decrypt(key, iv2, buffer, out, 0));
}

void test_platform_keys() {
    // The retail key is a fixed platform constant; a typo would make every
    // retail title decrypt to noise.
    const uint8_t expected[16] = {0x20, 0xB1, 0x85, 0xA5, 0x9D, 0x28, 0xFD, 0xC3,
                                  0x40, 0x58, 0x3F, 0xBB, 0x08, 0x96, 0xBF, 0x91};
    assert(same(kXexRetailKey, expected, 16));
    for (std::size_t index = 0; index < 16; ++index)
        assert(kXexDevkitKey[index] == 0);
}

} // namespace

int main() {
    test_fips197_appendix_c1();
    test_fips197_appendix_b();
    test_in_place_block_operation();
    test_cbc_vector_sp800_38a();
    test_cbc_chains_across_calls();
    test_cbc_in_place_and_bad_sizes();
    test_platform_keys();
    std::printf("aes_test: all checks passed\n");
    return 0;
}
