constexpr uint8_t kRcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08, 0x10,
                               0x20, 0x40, 0x80, 0x1b, 0x36};

// Multiply in GF(2^8) with the AES reduction polynomial.
uint8_t gf_mul(uint8_t a, uint8_t b) noexcept {
    uint8_t result = 0;
    while (b) {
        if (b & 1) result ^= a;
        const uint8_t high = a & 0x80;
        a = static_cast<uint8_t>(a << 1);
        if (high) a ^= 0x1b;
        b >>= 1;
    }
    return result;
}

void expand_key(const uint8_t key[kAesKeySize],
                uint8_t schedule[kExpanded]) noexcept {
    std::memcpy(schedule, key, kAesKeySize);
    for (std::size_t index = kAesKeySize; index < kExpanded; index += 4) {
        uint8_t word[4];
        std::memcpy(word, schedule + index - 4, 4);
        if (index % kAesKeySize == 0) {
            // Rotate, substitute, then fold in the round constant.
            const uint8_t first = word[0];
            word[0] = static_cast<uint8_t>(kSbox[word[1]] ^
                                           kRcon[index / kAesKeySize]);
            word[1] = kSbox[word[2]];
            word[2] = kSbox[word[3]];
            word[3] = kSbox[first];
        }
        for (std::size_t byte = 0; byte < 4; ++byte)
            schedule[index + byte] =
                static_cast<uint8_t>(schedule[index - kAesKeySize + byte] ^
                                     word[byte]);
    }
}

void add_round_key(uint8_t state[16], const uint8_t* round_key) noexcept {
    for (std::size_t index = 0; index < 16; ++index) state[index] ^= round_key[index];
}

// The state is column-major: byte (row, col) lives at state[col * 4 + row].
void sub_bytes(uint8_t state[16], const uint8_t* box) noexcept {
    for (std::size_t index = 0; index < 16; ++index) state[index] = box[state[index]];
}

void shift_rows(uint8_t state[16]) noexcept {
    uint8_t temp[16];
    std::memcpy(temp, state, 16);
    for (std::size_t row = 1; row < 4; ++row)
        for (std::size_t col = 0; col < 4; ++col)
            state[col * 4 + row] = temp[((col + row) % 4) * 4 + row];
}

void inv_shift_rows(uint8_t state[16]) noexcept {
    uint8_t temp[16];
    std::memcpy(temp, state, 16);
    for (std::size_t row = 1; row < 4; ++row)
        for (std::size_t col = 0; col < 4; ++col)
            state[((col + row) % 4) * 4 + row] = temp[col * 4 + row];
}

void mix_columns(uint8_t state[16]) noexcept {
    for (std::size_t col = 0; col < 4; ++col) {
        uint8_t* c = state + col * 4;
        const uint8_t a0 = c[0], a1 = c[1], a2 = c[2], a3 = c[3];
        c[0] = static_cast<uint8_t>(gf_mul(a0, 2) ^ gf_mul(a1, 3) ^ a2 ^ a3);
        c[1] = static_cast<uint8_t>(a0 ^ gf_mul(a1, 2) ^ gf_mul(a2, 3) ^ a3);
        c[2] = static_cast<uint8_t>(a0 ^ a1 ^ gf_mul(a2, 2) ^ gf_mul(a3, 3));
        c[3] = static_cast<uint8_t>(gf_mul(a0, 3) ^ a1 ^ a2 ^ gf_mul(a3, 2));
    }
}

void inv_mix_columns(uint8_t state[16]) noexcept {
    for (std::size_t col = 0; col < 4; ++col) {
        uint8_t* c = state + col * 4;
        const uint8_t a0 = c[0], a1 = c[1], a2 = c[2], a3 = c[3];
        c[0] = static_cast<uint8_t>(gf_mul(a0, 0x0e) ^ gf_mul(a1, 0x0b) ^
                                    gf_mul(a2, 0x0d) ^ gf_mul(a3, 0x09));
        c[1] = static_cast<uint8_t>(gf_mul(a0, 0x09) ^ gf_mul(a1, 0x0e) ^
                                    gf_mul(a2, 0x0b) ^ gf_mul(a3, 0x0d));
        c[2] = static_cast<uint8_t>(gf_mul(a0, 0x0d) ^ gf_mul(a1, 0x09) ^
                                    gf_mul(a2, 0x0e) ^ gf_mul(a3, 0x0b));
        c[3] = static_cast<uint8_t>(gf_mul(a0, 0x0b) ^ gf_mul(a1, 0x0d) ^
                                    gf_mul(a2, 0x09) ^ gf_mul(a3, 0x0e));
    }
}

