void aes128_encrypt_block(const uint8_t key[kAesKeySize],
                          const uint8_t input[kAesBlockSize],
                          uint8_t output[kAesBlockSize]) noexcept {
    uint8_t schedule[kExpanded];
    expand_key(key, schedule);
    uint8_t state[16];
    std::memcpy(state, input, 16);

    add_round_key(state, schedule);
    for (int round = 1; round < kRounds; ++round) {
        sub_bytes(state, kSbox);
        shift_rows(state);
        mix_columns(state);
        add_round_key(state, schedule + round * 16);
    }
    sub_bytes(state, kSbox);
    shift_rows(state);
    add_round_key(state, schedule + kRounds * 16);
    std::memcpy(output, state, 16);
}

void aes128_decrypt_block(const uint8_t key[kAesKeySize],
                          const uint8_t input[kAesBlockSize],
                          uint8_t output[kAesBlockSize]) noexcept {
    uint8_t schedule[kExpanded];
    expand_key(key, schedule);
    uint8_t state[16];
    std::memcpy(state, input, 16);

    add_round_key(state, schedule + kRounds * 16);
    for (int round = kRounds - 1; round >= 1; --round) {
        inv_shift_rows(state);
        sub_bytes(state, kInvSbox);
        add_round_key(state, schedule + round * 16);
        inv_mix_columns(state);
    }
    inv_shift_rows(state);
    sub_bytes(state, kInvSbox);
    add_round_key(state, schedule);
    std::memcpy(output, state, 16);
}

bool aes128_cbc_decrypt(const uint8_t key[kAesKeySize],
                        uint8_t iv[kAesBlockSize], const uint8_t* input,
                        uint8_t* output, std::size_t size) noexcept {
    if (size % kAesBlockSize != 0) return false;
    if (size == 0) return true;
    if (!key || !iv || !input || !output) return false;

    uint8_t previous[kAesBlockSize];
    std::memcpy(previous, iv, kAesBlockSize);
    for (std::size_t offset = 0; offset < size; offset += kAesBlockSize) {
        // Keep the ciphertext before decrypting, so in-place operation works.
        uint8_t cipher[kAesBlockSize];
        std::memcpy(cipher, input + offset, kAesBlockSize);
        aes128_decrypt_block(key, cipher, output + offset);
        for (std::size_t index = 0; index < kAesBlockSize; ++index)
            output[offset + index] ^= previous[index];
        std::memcpy(previous, cipher, kAesBlockSize);
    }
    // Publish the chaining state so the next call continues the stream.
    std::memcpy(iv, previous, kAesBlockSize);
    return true;
}

